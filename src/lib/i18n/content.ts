export function localizeBusiness(
  lang: Lang,
  b: { slug: string; name: string; description: string; group: string },
): Entry {
  if (lang === "en") return { name: b.name, description: b.description, group: b.group };
  const src = lang === "ar" ? ar : fr;
  const groups = lang === "ar" ? groupsAr : groupsFr;
  const entry = src[b.slug];
  return {
    name: entry?.name ?? b.name,
    description: entry?.description ?? b.description,
    group: groups[b.group] ?? b.group,
  };
}

